let lang = "ru"
//см. шапку: сохранённый выбор → у существующих сейвов русский, у свежих — язык браузера
function detectLang() {
    let saved = null
    try {
        saved = JSON.parse(localStorage.getItem("settings"))
    } catch (e) {
        saved = null
    }
    if (saved && typeof saved === "object") {
        return saved.lang === "en" ? "en" : "ru"
    }
    let nav = (typeof navigator !== "undefined" && typeof navigator.language === "string") ? navigator.language : "ru"
    return nav.toLowerCase().indexOf("ru") === 0 ? "ru" : "en"
}
function setLang(l) {
    lang = l === "en" ? "en" : "ru"
}
function getLang() {
    return lang
}
function T(key, ...args) {
    let pair = MAP[key]
    let s
    if (!pair) {
        s = key
    } else if (lang === "en") {
        s = pair[2] !== undefined ? pair[2] : pair[1]
    } else {
        s = pair[1]
    }
    for (let i = 0; i < args.length; i++) {
        s = s.split("{" + i + "}").join(String(args[i]))
    }
    return s
}
//V58: имя предмета строкой. title/prefix/postfix предмета — КЛЮЧИ локализации (itemGenerate);
//у вещей из старых сохранений title — русская строка: её нет в словаре, T() вернёт её как есть.
//Строка собирается ТОЛЬКО при показе — смена языка меняет имена вещей живого инвентаря.
function itemName(item) {
    if (!item) return ""
    let s = item.prefix ? T(item.prefix) + " " : ""
    s += T(item.title)
    if (item.postfix) s += T(item.postfix)
    return s
}
