//V63: спрайт ловушки по её состоянию. Кислотная ловушка (спрайт 4) состояний не имеет;
//шипастая (3) и огненная (1) переключаются фазами раз в 2 секунды (логика — trapsFx.js):
//obj[13] === 0 — «выключенное» состояние, спрайт Ne.png (3e/1e), obj[13] === 1 —
//активное/горящее, спрайт N.png. Обезвреживание (useObject) ставит Nd.png, минуя e-состояние.
//Модуль БЕЗ импортов: его подключают sceneGenerate, mapRender, enemyHover и trapsFx,
//и циклов он не создаёт. obj[10] у старых объектов мог не записаться — фолбэк 3 (шипы).
function trapSpriteSrc(o) {
    let s = o[10] || 3
    return "./images/dungeon/traps/" + s + ((s === 3 || s === 1) && o[13] === 0 ? "e" : "") + ".png"
}
export {trapSpriteSrc}
